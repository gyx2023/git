-- 沃TV到期预警详情表（参照 wide_sys_auto_warning）
CREATE TABLE wotv_expire_warning (
    id              INT NOT NULL AUTO_INCREMENT COMMENT '主键',
    area_name       VARCHAR(255) DEFAULT NULL COMMENT '地市',
    county_name     VARCHAR(255) DEFAULT NULL COMMENT '经营单元',
    svc_num         VARCHAR(255) DEFAULT NULL COMMENT '业务号码',
    user_id         VARCHAR(255) DEFAULT NULL COMMENT '用户编号',
    cust_name       VARCHAR(255) DEFAULT NULL COMMENT '用户姓名',
    cust_grp_id     INT DEFAULT NULL COMMENT '收入归集编码',
    service_name    VARCHAR(255) DEFAULT NULL COMMENT '业务类型名称',
    conn_type       VARCHAR(255) DEFAULT NULL COMMENT '宽带接入方式',
    scheme_id       INT DEFAULT NULL COMMENT '活动ID',
    scheme_name     VARCHAR(255) DEFAULT NULL COMMENT '活动名称',
    eff_time        DATETIME DEFAULT NULL COMMENT '活动生效时间',
    exp_time        DATETIME DEFAULT NULL COMMENT '活动失效时间',
    amount_per_year VARCHAR(255) DEFAULT NULL COMMENT '年费,单位元',
    rate_           VARCHAR(255) DEFAULT NULL COMMENT '宽带速率,单位M',
    user_addr       VARCHAR(500) DEFAULT NULL COMMENT '安装地址',
    contact_man     VARCHAR(255) DEFAULT NULL COMMENT '联系人',
    contact_phone   VARCHAR(255) DEFAULT NULL COMMENT '联系电话',
    warm_type       INT DEFAULT NULL COMMENT '预警类型(1提前2月/2提前1月/3当月≤5000/4当月>5000/5逾期1月/0不做预警)',
    exte_flag       INT DEFAULT NULL COMMENT '是否续约(1是/0否)',
    grp_code        VARCHAR(255) DEFAULT NULL COMMENT '集团15位编码',
    grp_name        VARCHAR(255) DEFAULT NULL COMMENT '集团客户名称',
    serv_manager_id VARCHAR(255) DEFAULT NULL COMMENT '客户经理编码',
    u_id            INT DEFAULT NULL COMMENT '用户通用级预警Id',
    main_order_flow_no VARCHAR(255) DEFAULT NULL COMMENT '主订单流水',
    order_flow_no    VARCHAR(255) DEFAULT NULL COMMENT '子订单流水',
    WARNING_LEVEL    VARCHAR(10) DEFAULT NULL COMMENT '预警优先级',
    DISCNT_CODE      INT DEFAULT NULL COMMENT '续约活动ID',
    NEW_ACCEPT_DATE  DATETIME DEFAULT NULL COMMENT '续约时间',
    NEW_EFF_TIME     DATETIME DEFAULT NULL COMMENT '续约活动生效时间',
    NEW_EXP_TIME     DATETIME DEFAULT NULL COMMENT '续约活动失效时间',
    DEVELOPER_ID     VARCHAR(255) DEFAULT NULL COMMENT '发展人编码',
    DEVELOPER_NAME   VARCHAR(255) DEFAULT NULL COMMENT '发展人名称',
    LVL_NAME         VARCHAR(255) DEFAULT NULL COMMENT '业务大类',
    RELATION_TYPE_NAME VARCHAR(255) DEFAULT NULL COMMENT '融合类型名称',
    IS_NINEDISCOUNT  VARCHAR(10) DEFAULT NULL COMMENT '是否叠加9折包',
    LAST_BALANCE     VARCHAR(255) DEFAULT NULL COMMENT '上月余额',
    LAST_BILL_FEE    VARCHAR(255) DEFAULT NULL COMMENT '上月出账费用',
    IS_RED_LIST      VARCHAR(10) DEFAULT NULL COMMENT '是否红名单',
    create_date      DATETIME DEFAULT NULL COMMENT '创建日期',
    PRIMARY KEY (id),
    INDEX idx_u_id (u_id),
    INDEX idx_create_date (create_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='沃TV到期预警详情表';
