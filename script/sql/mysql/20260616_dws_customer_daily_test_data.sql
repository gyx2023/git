-- 用于 SEMANTIC_QUERY 路由的"新增客户"指标测试

CREATE TABLE IF NOT EXISTS `dws_customer_daily` (
  `stat_date`     date         NOT NULL COMMENT '统计日期',
  `create_month`  varchar(7)   NOT NULL COMMENT '创建月份（yyyy-MM）',
  `region_code`   varchar(20)  DEFAULT NULL COMMENT '区域编码',
  `dept_id`       bigint(20)   DEFAULT NULL COMMENT '部门ID',
  `customer_id`   bigint(20)   NOT NULL COMMENT '客户ID',
  KEY `idx_create_month` (`create_month`),
  KEY `idx_region` (`region_code`),
  KEY `idx_dept` (`dept_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='客户每日新增宽表（测试用）';

